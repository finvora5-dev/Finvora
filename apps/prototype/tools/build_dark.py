"""Dark theme (owner approved 15 Nov 2026; colour set in the 'Finvora Dark Theme' approval page). Writes the dark rules
into responsive.css between the DARK markers. Boards keep their light inline colours; under html[data-fv-theme="dark"]
these rules override them by matching the rendered rgb() values. Usage: python3 build_dark.py <site folder>"""
import os, sys
SITE = sys.argv[1]; P = os.path.join(SITE, 'responsive.css')
def rgb(h): h = h.lstrip('#'); return 'rgb(%d, %d, %d)' % tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
D = 'html[data-fv-theme="dark"] #dc-root'
BG = {'#F8F9FA': '#0B192C', '#FFFFFF': '#1A2740', '#EEF0F3': '#22314A', '#EDEFF2': '#22314A', '#E8EBEF': '#22314A', '#E2E5EA': '#22314A',
      '#F0F0F3': '#22314A', '#D5D9E0': '#2C3D5B', '#DDF3E6': '#12352B', '#EAF6EF': '#12352B', '#FCEDEB': '#3A2023', '#FCEFED': '#3A2023', '#FBF0E2': '#3A2E1A'}
FG = {'#0B192C': '#F8F9FA', '#334155': '#B6C0CF', '#5B6577': '#C7D0DD', '#6B7486': '#8E9AAE', '#8A93A3': '#8E9AAE', '#047857': '#00E676', '#B9473F': '#F2A39C'}
BD = {'#E5E7EB': '#2C3D5B', '#D5D9E0': '#2C3D5B', '#E2E5EA': '#2C3D5B', '#EDEFF2': '#22314A', '#EEF0F3': '#22314A', '#0B192C': '#C7D0DD'}
SVG = {'#8A93A3': '#C7D0DD', '#6B7486': '#C7D0DD', '#F0F0F3': '#22314A', '#EEF0F3': '#22314A', '#0B192C': '#F8F9FA', '#047857': '#00E676', '#B9473F': '#F2A39C', '#5B6577': '#C7D0DD', '#E5E7EB': '#2C3D5B', '#E2E5EA': '#2C3D5B', '#D5D9E0': '#2C3D5B', '#EDEFF2': '#22314A'}
out = ['/* DARK:start (generated by tools/build_dark.py, do not edit by hand) */',
       'html[data-fv-theme="dark"] { color-scheme: dark; background: #0B192C; }',
       'html[data-fv-theme="dark"] body { background: #0B192C; color: #F8F9FA; }',
       D + ' a { color: #F8F9FA; }',
       D + ' ::placeholder { color: #8E9AAE; }']
for a, b in BG.items():
    r = rgb(a); out.append('%s [style*="background: %s"], %s [style*="background-color: %s"] { background-color: %s !important; }' % (D, r, D, r, b))
for a, b in FG.items():
    r = rgb(a); out.append('%s [style^="color: %s"], %s [style*="; color: %s"] { color: %s !important; }' % (D, r, D, r, b))
for a, b in BD.items():
    out.append('%s [style*="solid %s"] { border-color: %s !important; }' % (D, rgb(a), b))
for a, b in SVG.items():
    out.append('%s [stroke="%s" i] { stroke: %s; } %s [fill="%s" i]:not([role="img"] *) { fill: %s; }' % (D, a, b, D, a, b))
N = rgb('#0B192C')
out += [
  '/* Main buttons: navy would vanish on the navy page, so they turn emerald with navy text (approved). */',
  '%s a[style*="background: %s"], %s button[style*="background: %s"], %s a[style*="background-color: %s"], %s button[style*="background-color: %s"] { background-color: #00E676 !important; color: #0B192C !important; }' % (D, N, D, N, D, N, D, N),
  '%s a[style*="background: %s"] *, %s button[style*="background: %s"] *, %s a[style*="background-color: %s"] *, %s button[style*="background-color: %s"] * { color: #0B192C !important; stroke: #0B192C; }' % (D, N, D, N, D, N, D, N),
  '/* Navy headers stay navy; a thin line separates them from the navy page. */',
  '%s > .sc-host > :first-child > :is(div, header)[style*="background: %s"] { box-shadow: inset 0 -1px 0 #22314A; }' % (D, N),
  '/* Bottom nav: lighter bar with a border, since a shadow does not show on navy (approved). Ask keeps emerald. */',
  '%s nav[aria-label="Main"] [style*="background: %s"] { background-color: #1A2740 !important; box-shadow: inset 0 0 0 1px #2C3D5B; }' % (D, N),
  '%s nav[aria-label="Main"] a, %s nav[aria-label="Main"] a * { background-color: transparent; }' % (D, D),
  '%s nav[aria-label="Main"] { filter: none !important; }' % D,
  '%s nav[aria-label="Main"] [fill="#0B192C" i] { fill: #1A2740; stroke: #2C3D5B; stroke-width: 1px; }' % D,
  '/* Text boxes without their own background stay see-through (dark form defaults would grey them). */',
  '%s textarea, %s input { background-color: transparent; }' % (D, D),
  '/* Switches: emerald when on, off-white knob. */',
  '%s [role="switch"][aria-checked="true"] { background-color: #00E676 !important; }' % D,
  '%s [role="switch"] > span { background-color: #F8F9FA !important; }' % D,
  '/* Laptop sidebars and the Finvora logo tile are navy in both themes. */',
  '%s aside[style*="background: %s"] { box-shadow: inset -1px 0 0 #22314A; }' % (D, N),
  '%s [role="img"][aria-label="Finvora"] { background-color: #0B192C !important; }' % D,
  '/* DARK:end */']
s = open(P).read()
if '/* DARK:start' in s: a = s.index('/* DARK:start'); b = s.index('/* DARK:end */') + len('/* DARK:end */'); s = s[:a] + '\n'.join(out) + s[b:]
else: s = s.rstrip() + '\n' + '\n'.join(out) + '\n'
open(P, 'w').write(s); print('dark rules', len(out))
