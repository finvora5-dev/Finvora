"""Write apps/prototype/site/sw.js: offline support for the prototype site.
It stores every site file on first visit, serves fresh pages when online, and falls back to the stored
copy (or the "You're offline" screen) when there is no connection. Re-run after changing any site file
so the cache version changes. Usage: python3 build_sw.py <site folder>"""
import hashlib, os, sys, json
SITE = sys.argv[1]
files = sorted(f for f in os.listdir(SITE) if f.endswith(('.dc.html', '.js', '.css')) and f not in ('sw.js',))
h = hashlib.sha256()
for f in files: h.update(open(os.path.join(SITE, f), 'rb').read())
version = h.hexdigest()[:12]
js = '''// Generated by apps/prototype/tools/build_sw.py. Do not edit.
const VERSION = "fv-%s";
const FILES = %s;
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => Promise.all(FILES.map((f) => fetch("./" + f).then((r) => r.ok && c.put("./" + f, r.clone().redirected ? new Response(r.body, { headers: r.headers }) : r)).catch(() => {})))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== VERSION && k.startsWith("fv-")).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
function keyFor(url) { const u = new URL(url); let p = u.pathname.split("/").pop() || "index.html"; if (/\\.dc$/.test(p)) p += ".html"; return "./" + p; }
async function fromCache(req) { const c = await caches.open(VERSION); return (await c.match(keyFor(req.url))) || (await c.match(req, { ignoreSearch: true })); }
self.addEventListener("fetch", (e) => {
  const req = e.request; if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    e.respondWith((async () => {
      try {
        const r = await fetch(req, { cache: "no-cache" }); // always check for the newest file
        if (r.ok && req.mode !== "navigate") { const c = await caches.open(VERSION); c.put(keyFor(req.url), r.clone()); }
        return r;
      } catch (err) {
        const hit = await fromCache(req); if (hit) return hit;
        if (req.mode === "navigate") { const off = await caches.open(VERSION).then((c) => c.match("./UPOffline.dc.html")); if (off) return off; }
        throw err;
      }
    })());
  } else if (/fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname)) {
    e.respondWith(caches.open(VERSION + "-fonts").then(async (c) => (await c.match(req)) || fetch(req).then((r) => { c.put(req, r.clone()); return r; })));
  }
});
''' % (version, json.dumps(files))
open(os.path.join(SITE, 'sw.js'), 'w').write(js)
print('sw.js', version, len(files), 'files')
